#!/usr/bin/env python3
"""Generate Results-only original texture identities from read-only game assets.

Run with UnityPy available. --check compares the generated C# without writing it;
--report retains original addresses, payload hashes, sampling/color-space hashes
and explicit refusals. No game file is changed and no texture pixels are shipped.
"""
from __future__ import annotations

import argparse
from collections import defaultdict
import gc
import hashlib
import json
from pathlib import Path

import UnityPy

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'src/GloomhavenVR/Net/ScenarioResultsOriginalTextures.cs'
METADATA = ('m_TextureSettings', 'm_ColorSpace', 'm_TextureDimension',
            'm_ImageCount', 'm_LightmapFormat', 'm_MipsStripped', 'm_IsPreProcessed')


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def file_sha(path: Path) -> str:
    with path.open('rb') as source:
        return hashlib.file_digest(source, 'sha256').hexdigest()


def canonical(value) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(',', ':')).encode()


def audit(game_data: Path) -> dict:
    rows, files = [], []
    paths = sorted(path for path in game_data.iterdir() if path.is_file()
                   and (path.name.endswith('.assets')
                        or path.name.startswith('level') and not path.suffix))
    for path in paths:
        files.append({'file': path.name, 'bytes': path.stat().st_size,
                      'sha256': file_sha(path)})
        env = UnityPy.load(str(path))
        for obj in env.objects:
            if obj.type.name != 'Texture2D':
                continue
            data = obj.read_typetree()
            width, height = data['m_Width'], data['m_Height']
            # Deferred legacy fonts have no initial pixel stream. Attempting to
            # read their empty stream path as a file is neither useful nor safe.
            raw = obj.read().get_image_data() if width > 0 and height > 0 else b''
            metadata = {name: data[name] for name in METADATA if name in data}
            key = '|'.join(map(str, ('texture', data['m_Name'], width, height,
                                     data['m_TextureFormat'], data['m_MipCount'])))
            rows.append({'file': obj.assets_file.name, 'path_id': obj.path_id,
                         'key': key, 'name': data['m_Name'], 'width': width,
                         'height': height, 'format': data['m_TextureFormat'],
                         'mips': data['m_MipCount'],
                         'readable': data.get('m_IsReadable'),
                         'raw_bytes': len(raw), 'raw_sha256': sha(raw),
                         'metadata': metadata, 'metadata_sha256': sha(canonical(metadata))})
        del env
        gc.collect()
    rows.sort(key=lambda row: (row['file'], row['path_id']))
    allowed, refused = classify(rows)
    return {'schema': 'results-original-textures-v1', 'rows': rows, 'files': files,
            'allowed': allowed, 'refused': refused,
            'identity_boundary': 'Trusted original descriptors, not a live pixel-content comparison. '
                                 'Admission is opt-in for Results only; generated and unknown assets remain strict.'}


def classify(rows: list[dict]) -> tuple[list[dict], list[dict]]:
    groups = defaultdict(list)
    for row in rows:
        groups[row['key']].append(row)
    allowed, refused = [], []
    for key, group in sorted(groups.items()):
        first = group[0]
        if first['name'] == 'Font Texture':
            reason = 'mutable-legacy-font-atlas'
        elif first['width'] <= 0 or first['height'] <= 0 or first['raw_bytes'] <= 0:
            reason = 'nonpositive-or-empty'
        elif len({(row['raw_sha256'], row['metadata_sha256']) for row in group}) != 1:
            reason = 'different-original-content-or-sampling'
        else:
            reason = ''
        entry = {'key': key, 'originals': [
            {field: row[field] for field in ('file', 'path_id', 'raw_sha256', 'metadata_sha256')}
            for row in group]}
        if reason:
            refused.append({**entry, 'reason': reason})
        else:
            allowed.append(entry)
    return allowed, refused


def render(report: dict) -> str:
    fingerprint = sha(canonical({'rows': report['rows'], 'files': report['files']}))
    keys = '\n'.join('        ' + json.dumps(row['key'], ensure_ascii=True) + ','
                     for row in report['allowed'])
    return f'''// Generated by scripts/generate-results-native-texture-catalog.py; do not hand-edit.
// Original corpus: {len(report['files'])} serialized files, {len(report['rows'])} Texture2D objects.
// {len(report['allowed'])} static identities admitted; {len(report['refused'])} descriptor groups explicitly refused.
// Raw payload plus sampling/color-space corpus SHA256: {fingerprint}
using System;
using System.Collections.Generic;

namespace GloomhavenVR.Net;

/// <summary>Trusted native texture identities for the original Results picture only.
/// These keys identify audited serialized originals; they do not hash live GPU pixels.
/// Mutable legacy font atlases and conflicting original content retain strict resolution.
/// All other registries keep their existing identity rules.</summary>
internal static class ScenarioResultsOriginalTextures
{{
    internal static bool Contains(string descriptorKey) => Keys.Contains(descriptorKey);

    private static readonly HashSet<string> Keys = new(StringComparer.Ordinal)
    {{
{keys}
    }};
}}
'''


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--game-data', type=Path, default=ROOT / 'ressources/GH_Data')
    parser.add_argument('--output', type=Path, default=OUTPUT)
    parser.add_argument('--report', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    report = audit(args.game_data)
    generated = render(report)
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(report, indent=2) + '\n')
    if args.check:
        if not args.output.is_file() or args.output.read_text() != generated:
            raise SystemExit('Results original-texture catalog is stale: regenerate from the audited game assets.')
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(generated)
    print(f"Results native textures: {len(report['allowed'])} admitted, {len(report['refused'])} refused "
          f"from {len(report['rows'])} originals; {'checked' if args.check else 'generated'} {args.output}")
    return 0


if __name__ == '__main__':
    raise SystemExit(main())

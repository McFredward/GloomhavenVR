    /// quoted in <c>Clone.Gait</c>'s own doc). The clip picked here is the one
    /// <c>Clone.WalkClipSeconds</c> would pick — same names, same order.</para>
    /// </summary>
    private static float ImpliedSpeed(CClass.ENPCModel model) => model switch

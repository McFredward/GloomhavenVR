    /// <summary>
    /// Does this event's path pass through masonry? Returns the wall's name, or null.
    ///
    /// <para>The test is on the SEGMENT and is exact rather than sampled: a straight walk crosses an
    /// axis-aligned plane at most once, at a fraction that solves for one coordinate, so the crossing
    /// point is computed and tested against the slab's rectangle and its hole. Sampling would be the
    /// obvious implementation and is strictly worse — it can step over a 5 cm jamb.</para>
    ///
    /// <para>A path that does not move cannot cross anything and is answered in the first compare,
    /// which is what three of the four events are since this round.</para>
    /// </summary>
    private static string? PathCrossesWall(SkyStyle style, Vector3 from, Vector3 to)
    {
        if (style != SkyStyle.Cellar || from == to)
            return null;

        for (int i = 0; i < CellarWalls.Length; i++)
        {
            WallPlane w = CellarWalls[i];
            float a = w.Axis == 0 ? from.x : from.z;
            float b = w.Axis == 0 ? to.x : to.z;
            float da = a - w.At, db = b - w.At;
            if (da == 0f || db == 0f || (da > 0f) == (db > 0f))
                continue;                                  // both ends on the same side: no crossing

            float t = da / (da - db);
            Vector3 p = Vector3.Lerp(from, to, t);
            float u = w.Axis == 0 ? p.z : p.x;             // the in-plane horizontal coordinate
            if (u < w.Lo || u > w.Hi || p.y < w.YLo || p.y > w.YHi)
                continue;                                  // it passes the plane beyond the slab

            bool throughHole = w.HoleHi > w.HoleLo
                               && u >= w.HoleLo && u <= w.HoleHi
                               && p.y >= w.HoleYLo && p.y <= w.HoleYHi;
            if (throughHole)
                continue;                                  // a doorway is not a glitch

            return $"{w.Name} at {(w.Axis == 0 ? "x" : "z")} = {w.At:F2}, crossed at room-local "
                   + $"({p.x:F2}, {p.y:F2}, {p.z:F2})";
        }

        return null;
    }

    // =============================================================================================
    //  ARM → DRIVE → RETIRE. The life of one apparition.
    // =============================================================================================

    /// <summary>The node the figure hangs under, named <c>Haunt&lt;card&gt;</c>.</summary>
    private static GameObject? _anchor;

    /// <summary>Which way round the walk runs this time — a per-slot hash, so both clients agree.</summary>
    private static bool _reversed;

    /// <summary>
    /// The (card, start clock) pair of the last run <see cref="Arm"/> refused, so the reason is
    /// logged ONCE per run instead of once per frame.
    ///
    /// <para>THIS IS A DEFECT FIX AND NOT A TIDY-UP. When Arm bails it clears <c>_card</c>, and the
    /// driver's next frame sees <c>_card &lt; 0</c> with the slot's window still open and arms again
    /// — so a slot that cannot be cast, or a path that crosses a wall, wrote a log line at the frame
    /// rate for as long as the window lasted. At 90 Hz over a 5.5 s window that is five hundred
    /// copies of the same sentence, which is how a log stops being readable. The pair is unique per
    /// run, so a genuine second refusal (the next slot, or the next loop of a latch) still speaks.</para>
    /// </summary>
    private static int _quietCard = -1;
    private static float _quietStart = float.NaN;

    /// <summary>True the first time this exact run is refused; false for every repeat of it.</summary>
    private static bool AnnounceQuiet(int card)
    {
        if (_quietCard == card && _quietStart.Equals(_startClock))
            return false;
        _quietCard = card;
        _quietStart = _startClock;
        return true;
    }

    /// <summary>Resolved once at arm time and then held, so the figure cannot change species or
    /// facing mid-event if anything about the resolve ever became time-dependent.</summary>
    private static string _model = string.Empty;

    private static Quaternion _standRot = Quaternion.identity;

    /// <summary>THIS RUN'S path, in room-local metres — the authored one for a figure that stands,
    /// and the creature-derived one for a figure that travels (see THE CROSSING'S SPEED). Everything
    /// that positions the anchor reads these and not <c>ev.From</c>/<c>ev.To</c>, so there is exactly
    /// one place the two can differ.</summary>
    private static Vector3 _runFrom, _runTo;

    /// <summary>THIS RUN'S envelope multiplier: the schedule's <c>DurationMul</c> for a figure that
    /// stands, and <c>runSeconds / ev.Seconds</c> for one whose crossing was shortened to suit its
    /// own gait. It scales reveal, hold and fade TOGETHER, so a shorter run is the same shape played
    /// faster rather than a differently-shaped event — and it is never greater than
    /// <c>DurationMul</c>, which is what keeps the arming window in <see cref="TickBody"/> a valid
    /// upper bound without that side having to know any of this.</summary>
    private static float _shapeMul = 1f;

    /// <summary>
    /// Open the event: create the anchor node the audio cue looks for, decide the creature and the
    /// direction from the shared clock, and ask the clone factory to start loading. Nothing is
    /// visible yet — <see cref="ArmLeadSeconds"/> seconds of head start is the whole point.
    ///
    /// <para><b>THE ANCHOR NODE IS THE AUDIO INTEGRATION, AND IT IS THE ONLY ONE.</b>
    /// <c>EnvSound.HauntPosition</c> (EnvSound.cs:1001-1022) already looks for a descendant of the
    /// room root named exactly <c>Haunt0</c>…<c>Haunt5</c> and plays that card's cue from its
    /// renderer bounds — its doc comment says in as many words that it was written as a seam for
    /// "another lane rebuilding all twelve apparitions as real 3D geometry in this same round", and
    /// this is that lane. So the cue lands on the figure, and it FOLLOWS the figure as it walks,
    /// with not one line of coupling between the two files.</para>
    ///
    /// <para><b>IT IS CREATED PER EVENT AND DESTROYED WITH IT, deliberately.</b> A permanent set of
    /// <c>Haunt0</c>/<c>Haunt4</c> nodes would be cheaper, but <c>HauntPosition</c>'s SECOND
    /// fallback is "any descendant whose name starts with Haunt", and a permanent node would
    /// therefore capture the cues of the cards this lane does NOT own — silently moving the
    /// handprints' and the bookshelf's sounds onto the window. Existing only during our own slot
    /// leaves every other card's behaviour byte-identical to today's.</para>
    /// </summary>
    private static void Arm(SkyStyle style, int card, float slotIndex)
    {
        HauntEvent ev = EventFor(style, card);

        // WHICH WAY ROUND — hash channel 10. Channels 0/1/3/4/5/6/7 are the schedule's own
        // (Haunt.Schedule.cs), 2 is EnvSound's per-event variation and 13 is the rat's stare, so
        // 9/10/11 are this feature's and nothing else reads them. Deterministic, therefore shared.
        _reversed = Haunt.Hash(slotIndex, 10f) >= 0.5f;

        // WHICH CREATURE — a PERMUTATION of the cast, iterated by the APPARITION ORDINAL rather than
        // drawn from a hash of the slot. See Roster.Pick for the shuffle and for why consecutive
        // apparitions can never repeat, and ApparitionOrdinal for why it is not the slot index. Both
        // are pure functions of the shared clock's slot, so two clients cannot disagree.
        float ordinal = ApparitionOrdinal(style, slotIndex);
        _model = Roster.Pick(ev.Cast, ordinal, out CClass.ENPCModel picked);
        if (_model.Length == 0)
        {
            // Nothing in this event's cast is available. ONE line, and the slot is simply quiet —
            // the mask has already suppressed the shader card for this room, so the honest outcome
            // is a quiet slot rather than a substitute creature that was never designed for the
            // framing. The next slot tries again. ONE line per RUN and not per frame — see
            // AnnounceQuiet for why that guard had to be added.
            if (AnnounceQuiet(card))
                VRLog.Info("Core", $"HAUNT FIGURES: {style} card {card} ({ev.Name}) is quiet this slot — none of "
                               + $"its cast ({Roster.Describe(ev.Cast)}) resolved to a base-game enemy prefab "
                               + "on this machine. No apparition rather than a wrong one.");
            _card = -1;
            return;
        }

        // ---- THIS RUN'S PATH AND THIS RUN'S LENGTH, derived from the creature ---------------------
        //
        // See THE CROSSING'S SPEED above CrossBlendTarget for the rule and for the user report that
        // produced it. A figure that stands keeps the authored path and the authored length exactly;
        // a figure that travels keeps the authored path's CENTRE and DIRECTION and gets a length of
        // its own. Both bounds can only shorten the event, never lengthen it.
        float authoredSeconds = Mathf.Max(ev.Seconds * _durMul, 0.01f);
        float implied = ImpliedSpeed(picked);
        float speed = 0f;
        if (ev.From == ev.To)
        {
            _runFrom = ev.From;
            _runTo = ev.To;
            _shapeMul = _durMul;
        }
        else
        {
            Vector3 centre = (ev.From + ev.To) * 0.5f;
            Vector3 along = ev.To - ev.From;
            along.y = 0f;
            Vector3 unit = along.sqrMagnitude > 1e-6f ? along.normalized : Vector3.forward;

            float want = Mathf.Max(implied * CrossBlendTarget, 0.05f);
            float metres = Mathf.Clamp(want * authoredSeconds, CrossMinMetres, CrossMaxMetres);
            float runSeconds = Mathf.Clamp(metres / want, CrossMinSeconds, authoredSeconds);

            _runFrom = centre - unit * (metres * 0.5f);
            _runTo = centre + unit * (metres * 0.5f);
            _shapeMul = runSeconds / Mathf.Max(ev.Seconds, 0.01f);
            speed = metres / runSeconds;
        }

        // THE WALL GATE, ON THE PATH THAT WILL ACTUALLY BE WALKED. See the block above CellarWalls
        // for why this is arithmetic and not a comment: the event it exists to catch shipped behind a
        // doc paragraph that asserted the opposite of what its own coordinates did. It is checked
        // AFTER the derivation above rather than before it, because a derived path is longer than the
        // authored one and a gate on the authored one would be a gate on a path nobody walks.
        // Refused, not clamped — the slot is quiet and the schedule tries again.
        string? wall = PathCrossesWall(style, _runFrom, _runTo);
        if (wall != null)
        {
            if (AnnounceQuiet(card))
                VRLog.Warn("Core", $"HAUNT FIGURES: {style} card {card} ({ev.Name}) is REFUSED — its path from "
                               + $"room-local {_runFrom:F2} to {_runTo:F2} passes through {wall}. A figure may "
                               + "not walk through masonry (user, verbatim: \"Die figuren sollten nicht durch "
                               + "wände glitchen\"), so this slot is quiet rather than showing it. The path is "
                               + "authored in HauntFigures.Events.cs — with its LENGTH derived from the "
                               + "creature since ModBuild 152 — and the walls are mirrored from "
                               + "BuildEnvironmentRooms.cs — if the bake moved a wall, that mirror is what "
                               + "needs to follow.");
            _card = -1;
            return;
        }

        _anchor = new GameObject("Haunt" + card);
        _anchor.transform.SetParent(_room, worldPositionStays: false);
        Vector3 start = PathAt(style, 0f);
        _anchor.transform.localPosition = start;

        // FACING. Three cases, all resolved ONCE here, in room-local space, and never touched
        // again: an authored direction if the event names one (the window figure looks INTO the
        // room, the stair figure looks OUT through its doorway), otherwise "toward the clearing"
        // for a figure that stands where nothing was authored (the forest watcher), otherwise "the
        // way you walk" for one that travels.
        // NOTHING IN THIS FEATURE MAY EVER RE-ORIENT WITH HEAD MOVEMENT (permanent project rule):
        // there is no camera read anywhere in this file, and a facing derived from the walk cannot
        // acquire one by accident.
        Vector3 dir = ev.From == ev.To
            ? (ev.Face != Vector3.zero ? ev.Face : new Vector3(-ev.From.x, 0f, -ev.From.z))
            : (_reversed ? _runFrom - _runTo : _runTo - _runFrom);
        dir.y = 0f;
        _standRot = dir.sqrMagnitude > 1e-6f
            ? Quaternion.LookRotation(dir.normalized, Vector3.up)
            : Quaternion.identity;
        _anchor.transform.localRotation = _standRot;

        // THE ROOM ROOT RIDES ALONG, and only for its LIGHT. The clone factory reads the room's
        // baked rig (_AmbUp/_DirDir/_L*Pos, written per material by BuildEnvironmentRooms.ApplyRig)
        // off one of its materials so the apparition can be lit by the same moon and the same
        // candles as the wall behind it — see the Lighting block in HauntFigures.Clone.cs for why
        // that is read back rather than mirrored, and why it is delivered as per-renderer SH rather
        // than as real Unity lights. The style goes with it because the two rooms answer the element
        // channel differently and _GhvrIndoor is what tells them apart on the GPU side.
        Clone.Request(_model, picked, ev, _anchor.transform, _room, style, speed, implied);

        float travel = (PathAt(style, 1f) - start).magnitude;
        float runSecondsLog = ev.Seconds * _shapeMul;
        VRLog.Info("Core", $"HAUNT FIGURES: {style} card {card} ({ev.Name}) armed at shared clock "
                           + $"{_startClock:F2}s for {runSecondsLog:F2}s — model '{_model}' ({picked}), "
                           + (ev.From == ev.To
                                  ? $"STANDING at room-local {start:F2}, facing {_standRot.eulerAngles.y:F0} deg"
                                  : $"walking {(_reversed ? "the other way" : "the authored way")}, room-local "
                                    + $"{start:F2} to {PathAt(style, 1f):F2}"
                                    // THE GAIT NUMBER, and it is here because it is the one thing a
                                    // hardware round can compare against and this file cannot: the
                                    // CLIP's own implied speed is inside an asset bundle, and a
                                    // mismatch between it and the path is foot slide. The census line
                                    // prints the clip lengths beside this one, so a reader has both
                                    // halves in the same log.
                                    + $" — {travel:F2} m in {runSecondsLog:F2}s = {speed:F2} m/s. "
                                    + "SINCE ModBuild 152 THE PATH IS DERIVED FROM THE CREATURE AND "
                                    + "NOT THE OTHER WAY ROUND (user: \"dann mach die Bewegung auch "
                                    + $"schneller\"): this one implies {implied:F2} m/s at full blend, "
                                    + $"so it is driven at {CrossBlendTarget:F2} of that and the "
                                    + $"authored {(ev.To - ev.From).magnitude:F2} m over "
                                    + $"{ev.Seconds * _durMul:F2}s became {travel:F2} m over "
                                    + $"{runSecondsLog:F2}s, bounded to "
                                    + $"[{CrossMinMetres:F1}, {CrossMaxMetres:F1}] m and at least "
                                    + $"{CrossMinSeconds:F2}s. RunBlend is NO LONGER the authored "
                                    + $"constant it was through ModBuild 149 ({ev.RunBlend:F2} at "
                                    + "every speed, for every creature) and should now land near "
                                    + $"{CrossBlendTarget:F2} — see the HAUNT FIGURES gait line, "
                                    + "which also prints how far the arm-time estimate above was "
                                    + "from the prefab's real numbers")
                           + $". THE CREATURE IS A SHUFFLED ITERATION and no longer a draw: it is "
                           + $"element {(int)ordinal % Mathf.Max(ev.Cast.Length, 1)} of a permutation "
                           + $"of this event's cast ({Roster.Describe(ev.Cast)}) that is reshuffled "
                           + $"every {ev.Cast.Length} apparitions, indexed by APPARITION ORDINAL "
                           + $"{ordinal:F0} (not by slot {slotIndex:F0} — see ApparitionOrdinal for "
                           + "why that distinction is the whole fix) on hash channel 11, while the "
                           + "direction stays a hash of the slot on channel 10. Every creature "
                           + "appears once before any appears twice, no two consecutive apparitions "
                           + "of this room can be the same one, and every input is a pure function of "
                           + "the shared clock's slot — so both clients pick the same creature with "
                           + "ZERO wire traffic and no 'last shown' state exists to drift. Its albedo "
                           + "is multiplied down to the room's own light level while it is up — see "
                           + "the HAUNT FIGURES light level line.");
    }

    /// <summary>
    /// One frame of a running apparition: where it is, which way it faces, how present it is, and
    /// whether it should still exist. All of it is a function of the shared clock and nothing else.
    /// </summary>
    private static void Drive(SkyStyle style, float clock)
    {
        HauntEvent ev = EventFor(style, _card);
        // _shapeMul AND NOT _durMul: a crossing whose length was cut to suit a fast creature has to
        // spend its envelope over the length it actually runs, or the figure would still be at half
        // presence when its walk has finished. They are the same number for every standing event and
        // for any creature whose gait does not shorten the run. See _shapeMul.
        float len = Mathf.Max(ev.Seconds * _shapeMul, 0.05f);
        float t = clock - _startClock;

        // Before the start the figure is loading and MUST NOT be visible: the anchor exists (so the
        // audio cue can find it) but presence is 0, which the clone factory reads as "stay hidden".
        float u = Mathf.Clamp01(t / len);
        float presence = Envelope(t, ev, _shapeMul) * EdgeFade(t, ev, len);

        // ---- THE NO-BACKWARDS-STEP INTERLOCK ---------------------------------------------------
        //
        // TWO GUARDS, BOTH OF WHICH SET PRESENCE TO ZERO — i.e. both of which switch the RENDERERS
        // OFF (Clone.Shade), because "not drawn" is the only honest way to express "it is not there
        // yet". The whole argument, including the measured margin the envelope already provides, is
        // in the block at HauntFigures._quietUntil.
        //
        //  1. A RESTARTED RUN IS BLANKED. The loop moves _startClock forward, so the anchor snaps
        //     from the end of the path back to its start in one frame; nothing may be drawn across
        //     that frame or for a few after it.
        //  2. A RUN NEVER GOES BACKWARDS. Within one run u = t/len and the clock only moves forward,
        //     so this can only fire if that construction is ever broken — and if it is, the figure
        //     is hidden for that frame rather than being drawn behind where it was.
        //
        // The ANCHOR is moved either way, deliberately: the audio cue follows the anchor and the
        // event's sound belongs to where the thing IS, not to where it was last drawn.
        if (clock < _quietUntil || (_lastDrivenU >= 0f && u < _lastDrivenU - 1e-4f))
            presence = 0f;
        else
            _lastDrivenU = u;

        if (_anchor != null)
            _anchor.transform.localPosition = PathAt(style, u);

        Clone.Drive(presence, ev.RunBlend);
    }

    /// <summary>
    /// The presence envelope — the C# twin of <c>GhvrHauntEnvelope</c> (EnvHaunt.cginc:310), kept
    /// deliberately identical in SHAPE so a figure and the shader apparitions in the same room read
    /// as one family: a smoothstep up over <c>reveal</c>, a hold, and either a smoothstep down or,
    /// when <c>fade</c> is zero, a hard step. The hard step is not an optimisation — it is the
    /// instant vanish the watcher is built around, and the cginc's own comment explains why it must
    /// be a real step rather than a collapsed smoothstep.
    ///
    /// <para>It is a TWIN and not a mirror: nothing depends on the two agreeing to the bit, because
    /// they never shade the same pixel. That is why this one is allowed to be a re-implementation
    /// while <see cref="Haunt.Resolve"/> is held to being character-for-character the shader's.</para>
    /// </summary>
    private static float Envelope(float t, in HauntEvent ev, float mul)
    {
        float r = Mathf.Max(ev.Reveal * mul, 1e-4f);
        float h = ev.Hold * mul;
        float f = ev.Fade * mul;
        if (t <= 0f)
            return 0f;
        float up = Mathf.SmoothStep(0f, 1f, Mathf.Clamp01(t / r));
        float down = f > 1e-4f
            ? Mathf.SmoothStep(0f, 1f, Mathf.Clamp01((r + h + f - t) / f))
            : (t <= r + h ? 1f : 0f);
        return Mathf.Clamp01(up * down);
    }

    /// <summary>
    /// A SHORT APPEARANCE AND A SHORT DISSOLUTION THAT NO EVENT CAN AUTHOR AWAY.
    ///
    /// <para><b>USER REPORT, ModBuild 150, verbatim:</b> "Das Verschwinden und Auftauchen der Figuren
    /// geschieht aktuell abrupt von einem Frame auf den anderen. Ich hätte gerne eine kurze
    /// Erscheinen- bzw. Auflösen-Animation."</para>
    ///
    /// <para><b>THE DISAPPEARANCE HALF IS LITERAL AND IT IS IN THIS FILE.</b> Two of the four events
    /// are authored <c>fade: 0.00f</c> — the cellar stair figure (:288) and the treeline watcher
    /// (:326) — and <see cref="Envelope"/> honours that with a real step
    /// (<c>t &lt;= r + h ? 1f : 0f</c>), which was a deliberate design choice recorded as "the instant
    /// vanish the watcher is built around". The user has now looked at it on hardware and asked for
    /// the opposite, so the step goes: this multiplier gives every figure at least
    /// <see cref="EdgeSeconds"/> of dissolve whatever its event says. The SHADER-drawn apparitions
    /// keep their instant vanish — <c>GhvrHauntEnvelope</c> is untouched — because nothing about them
    /// was reported.</para>
    ///
    /// <para><b>IT ONLY EVER SHORTENS THE FIGURE'S PRESENCE, NEVER LENGTHENS THE EVENT.</b> It is a
    /// multiplier in 0..1 applied on top of the envelope, and its ramps are clamped to a third of the
    /// run so a very short slot cannot end up as nothing but edges. An event that already fades over
    /// 0.60 s or 0.80 s is unaffected in practice: its own envelope is below this ramp for the whole
    /// overlap.</para>
    ///
    /// <para><b>WHY 0.35 s AND WHY IT CANNOT READ AS A LOADING BUG.</b> It is comfortably under the
    /// 0.6 s the brief asks for at each end, so it reads as an event rather than as a wait. And it is
    /// a change in BRIGHTNESS of the whole figure at once — the tint is one colour per material
    /// (<c>Clone.Shade</c>) — so there is no moment at which part of the creature is present and part
    /// is not. That is the entire distinction from the ModBuild 148 noise-field dissolve the user read
    /// as half-streamed textures ("viele schwarze flecken in ihnen"), which this must not and does not
    /// resemble: no holes, no marbling, no per-texel anything. The second half of the same fix is
    /// <c>Clone.PerceptualGamma</c>, which stops the rising envelope from spending a third of its
    /// visible change in the first eighth of its time.</para>
    /// </summary>
    private static float EdgeFade(float t, in HauntEvent ev, float len)
    {
        float e = Mathf.Min(EdgeSeconds, len / 3f);
        if (e <= 1e-4f)
            return 1f;
        // The event's own ramps are already at least this long where they exist, so taking the
        // minimum of the two is a no-op there and the whole of the effect where fade is 0.
        float up = Mathf.SmoothStep(0f, 1f, Mathf.Clamp01(t / e));
        float down = Mathf.SmoothStep(0f, 1f, Mathf.Clamp01((len - t) / e));
        return Mathf.Clamp01(up * down);
    }

    /// <summary>The floor on a figure's appearance and dissolution, in seconds, at each end. See
    /// <see cref="EdgeFade"/>.</summary>
    private const float EdgeSeconds = 0.35f;

    /// <summary>Room-local position at walk fraction <paramref name="u"/>, with the forest's ground
    /// followed and the cellar's ignored (the cellar floor undulates by ±6 mm,
    /// BuildEnvironmentRooms.cs:1861 — below the threshold of anything).
    ///
    /// <para>It reads <see cref="_runFrom"/>/<see cref="_runTo"/> — THIS RUN's path — and not the
    /// event's authored one, because a crossing's length is derived from the creature (see THE
    /// CROSSING'S SPEED). The event is no longer a parameter for exactly that reason: it no longer
    /// holds the answer, and a signature that still took it would invite a caller to believe it
    /// did.</para></summary>
    private static Vector3 PathAt(SkyStyle style, float u)
    {
        Vector3 a = _reversed ? _runTo : _runFrom;
        Vector3 b = _reversed ? _runFrom : _runTo;
        Vector3 p = Vector3.Lerp(a, b, Mathf.Clamp01(u));
        if (style == SkyStyle.SwampNight)
            p.y = Ground.ForestY(p.x, p.z);
        return p;
    }

    /// <summary>Drop the running apparition and its anchor. Idempotent.</summary>
    private static void Retire(string why)
    {
        Clone.Release(why);
        if (_anchor != null)
        {
            Object.Destroy(_anchor);
            _anchor = null;
        }
        _card = -1;
        _model = string.Empty;
    }

    // =============================================================================================
    //  THE GROUND — a MIRROR of the forest's height field, and the argument for why it is one.
    // =============================================================================================

    /// <summary>
    /// The forest floor's height at a room-local (x, z).
    ///
    /// <para><b>WHY THIS IS A MIRROR AND NOT A MEASUREMENT.</b> Three ways to know the ground height
    /// under a figure were available and two of them are closed. (1) A RAYCAST needs a collider, and
    /// the room ships none — deliberately, so the hand laser can never catch the environment
    /// (SkyAlternative.cs's collider strip). Adding one would put 30 m of terrain in front of every
    /// pointer in the game. (2) SAMPLING THE GROUND MESH is closed too: reading vertices at runtime
    /// needs <c>Mesh.isReadable</c>, which costs a permanent CPU copy of the mesh, and the bake
    /// turns readability OFF for the assets it imports (BuildEnvironmentRooms.cs:210). (3) So the
    /// height field is mirrored, which is what is left, and it is exact rather than approximate.</para>
    ///
    /// <para><b>WHAT THE MIRROR COSTS, STATED PLAINLY.</b> This is the same class of debt
    /// <c>Haunt.Schedule.cs</c> records for the schedule hash, and the same guard applies: the lint
    /// <c>scripts/check-mirrors.sh</c> cannot cover it (it compares <c>const</c> declarations inside
    /// <c>src/</c>, and the other side of this pair is a private static method under <c>unity/</c>),
    /// so the guard is this comment plus the cited line numbers.
    /// <b>The other side is <c>BuildEnvironmentRooms.cs</c>: <c>ForestY</c> :7957-7981,
    /// <c>PathDist</c> :7942-7952, <c>PathFade</c> :7954-7955, <c>Fbm2</c> :970-979,
    /// <c>Noise2</c> :960-968, <c>Hash3</c> :950-958.</b> Whoever changes the forest's relief must
    /// change this block, and the failure mode if they do not is specific and visible: an apparition
    /// wading through the ground or floating above it at 13 m. It cannot cause a desync, a
    /// mismatch or a crash — every client runs the same mirror.</para>
    ///
    /// <para><b>FLOAT AND THIS ORDER OF OPERATIONS</b>, for the reason the schedule mirror gives:
    /// the bake computes in single precision and reassociating would give a number that is very
    /// nearly right, which is the worst kind.</para>
    /// </summary>
    private static class Ground
    {
        private static bool _logged;

        internal static void Forget() => _logged = false;


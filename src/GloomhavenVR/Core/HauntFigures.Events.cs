internal static partial class HauntFigures
{
    // =============================================================================================
    //  WHY EVERY COORDINATE BELOW IS A LANDMARK AND NOT A NUMBER SOMEBODY LIKED
    //
    //  The two rooms are generated by unity/.../Editor/BuildEnvironmentRooms.cs, and their
    //  interesting features are DERIVED rather than typed: the cellar window is a Rect that is then
    //  SNAPPED to the wall mesh's 0.16 m cell grid (SnappedHole, :2178), the stair doorway is a
    //  second such Rect on a different wall, and the forest's ground height at any point is a noise
    //  function (ForestY, :7957). An apparition placed at a number that merely LOOKS right is a
    //  figure standing 8 cm inside a door jamb, or floating 30 cm above a hillside, at 13 m, in the
    //  dark, where nobody can tell what is wrong — only that something is.
    //
    //  So every position here is quoted from the bake WITH ITS LINE, the snapped values are used
    //  where the bake snaps (the stair haunt's own comment at :7534-7539 says that 8 cm of error
    //  walks a figure through the jamb), and the forest's ground is not guessed at but MIRRORED —
    //  see the Ground block at the bottom of this file for why that mirror exists and what it costs.
    //
    //  THE ROOM FRAME. The room root is world-anchored, placed exactly once and never re-seated
    //  (SkyAlternative.cs:1443-1446 — re-seating a room the player stands in reads as a player
    //  teleport, ModBuild-131 ruling). Its transform is a yaw, a translation and a UNIFORM scale, so
    //  a figure parented to it and positioned in room-local metres is automatically at the room's
    //  own scale: a 2.6 m creature is 2.6 m against an 11.5 m tree and a 3.3 m ceiling, at every
    //  board zoom, with no scale tracking of any kind. That is the entire reason these events are
    //  authored in local space and parented rather than positioned in world space.
    // =============================================================================================

    /// <summary>
    /// One apparition, fully described. A STRUCT of plain data with no behaviour, because every
    /// field here is a design decision that has to be readable next to its neighbours — the moment
    /// an event needs code of its own it stops being comparable to the other three, and "why is this
    /// one different" becomes unanswerable.
    /// </summary>
    private readonly struct HauntEvent
    {
        /// <summary>The room's card index — the id the bake's HAUNT FORCE ID TABLE prints and the
        /// Advanced-menu test buttons use.</summary>
        internal readonly int Card;

        /// <summary>For the log. English; the player never sees it.</summary>
        internal readonly string Name;

        internal readonly float Reveal;
        internal readonly float Hold;
        internal readonly float Fade;

        /// <summary>Where the walk begins and ends, in ROOM-LOCAL metres. Equal for a figure that
        /// stands still. Y is ignored in the forest, where the ground is sampled per frame.</summary>
        internal readonly Vector3 From;
        internal readonly Vector3 To;

        /// <summary>Metres, room-authored. The clone is scaled by <c>Target / CharacterManager.Height</c>
        /// — the prefab states its own height, so this is a real height and not a guessed multiplier.
        /// 0 leaves the model at its authored size.</summary>
        internal readonly float Height;

        /// <summary>The animator's <c>RunBlend</c> float — a BLEND WEIGHT and not a speed
        /// (ActorBehaviour.cs:79, :546-547): 0 stands still, 1 is what the game itself drives during
        /// any sustained travel. See ANIMATION in HauntFigures.Clone.cs for why this and a transform
        /// of our own is the ONLY way to make a game monster travel.
        ///
        /// <para><b>SINCE ModBuild 150 THIS IS ONLY READ FOR A FIGURE THAT STANDS</b> — i.e. where
        /// it is 0 anyway. A figure that TRAVELS has its blend derived per apparition from the path's
        /// real speed, the creature's real scale and its own locomotion clip; the authored constant
        /// (0.55 for the forest crossing, at every speed and for every creature) was the whole of the
        /// user's teleport report. <c>Clone.Gait</c> carries the argument and the arithmetic. The
        /// field is kept because a future STANDING event may legitimately want a non-zero
        /// idle-shuffle, and because the log prints it beside the derived value so the two can be
        /// compared.</para></summary>
        internal readonly float RunBlend;

        /// <summary>Room-local direction the figure faces when it is not travelling. Zero means
        /// "face the way you are walking".</summary>
        internal readonly Vector3 Face;

        /// <summary>Enemy models to try, in order — the first one this machine can actually resolve
        /// wins. The per-slot hash rotates the starting point, so the list is a preference and not a
        /// fixed casting.</summary>
        internal readonly CClass.ENPCModel[] Cast;

        internal HauntEvent(int card, string name, float reveal, float hold, float fade,
                            Vector3 from, Vector3 to, float height, float runBlend, Vector3 face,
                            CClass.ENPCModel[] cast)
        {
            Card = card; Name = name;
            Reveal = reveal; Hold = hold; Fade = fade;
            From = from; To = to;
            Height = height; RunBlend = runBlend; Face = face;
            Cast = cast;
        }

        /// <summary>Authored length before the per-slot <see cref="Haunt.Slot.DurationMul"/>.</summary>
        internal float Seconds => Reveal + Hold + Fade;
    }

